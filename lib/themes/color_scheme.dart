  Color chatColorSelector(bool isMe, bool isSecretChat, {bool isDecryptFailed = false}) {
    if (isDecryptFailed) {
      return const Color(0xFFF6FCFF);
    }

    // isMe
    if (isMe && isSecretChat) {
      return secretRoomChatColor;
    }
    if (isMe && !isSecretChat) {
      return chatMessageOfMe;
    }

    //other
    if (isSecretChat) {
      return otherChatContainer;
    }
    return chatMessageOfOther;
  }

  Color chatTextColorSelector(bool isMe, bool isSecretChat) {
    // isMe
    if (isMe && isSecretChat) {
      return secretRoomText;
    }
    if (isMe && !isSecretChat) {
      return onChatMessageOfMe;
    }

    //other
    if (isSecretChat) {
      return onBackground;
    }
    return onChatMessageOfOther;
  }
