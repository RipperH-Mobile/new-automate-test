/// [AppRadius] is a class that contains all the radius used in the app.
///
/// The radius values are used to add radius to the widgets in the app.
class AppRadius {
  AppRadius._();

  /// The radius value `0` px
  static const double roundedNone = 0.0;

  /// The radius value `2` px
  static const double roundedSm = 2.0;

  /// The radius value `4` px
  static const double rounded = 4.0;

  /// The radius value `6` px
  static const double roundedMd = 6.0;

  /// The radius value `8` px
  static const double roundedLg = 8.0;

  /// The radius value `12` px
  static const double roundedXl = 12.0;

  /// The radius value `16` px
  static const double rounded2xl = 16.0;

  /// The radius value `24` px
  static const double rounded3xl = 24.0;

  /// The radius value `32` px
  static const double rounded4xl = 32.0;

  /// The radius value `999` px, used for full rounded corners
  static const double roundedFull = 999.0;
}
